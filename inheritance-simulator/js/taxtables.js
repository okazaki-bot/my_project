/* ---------- 表引きヘルパー ---------- */
function okuyukiRate(district, d){
  if(!(d>0)) return 1.00;
  for(const [lo,hi,r] of T_OKUYUKI) if(d>=lo&&d<hi) return r[district];
  return 1.00;
}
function maguchiRate(district, w){
  if(!(w>0)) return 1.00;
  for(const [lo,hi,r] of T_MAGUCHI) if(w>=lo&&w<hi){ const v=r[district]; return v==null?1.00:v; }
  return 1.00;
}
function okunagaRate(district, depth, front){
  if(!(depth>0&&front>0)) return 1.00;
  const ratio=depth/front;
  if(ratio<2) return 1.00;
  const col = district===0?0 : district<=3?1 : district===4?2 : district===5?3 : 4;
  for(const [lo,hi,r] of T_OKUNAGA) if(ratio>=lo&&ratio<hi) return r[col];
  return 1.00;
}
function sokuhoRate(district, junKado){ return T_SOKUHO[district][junKado?1:0]; }
function nihouRate(district){ return T_NIHOU[district]; }
function chisekiKubun(district, area){
  const k=T_CHISEKI_KUBUN[district];
  if(!k) return null;                       // 適用なし地区
  return area<k[0]?'A' : area<k[1]?'B' : 'C';
}
function fuseikeiRate(district, area, kagePct){
  if(kagePct<10) return 1.00;
  const kubun=chisekiKubun(district, area);
  if(!kubun) return 1.00;
  const g = district===4 ? T_FUSEIKEI.g2 : T_FUSEIKEI.g1;
  let idx=0;
  for(let i=0;i<T_FUSEIKEI_KAGE.length;i++) if(kagePct>=T_FUSEIKEI_KAGE[i]) idx=i;
  return g[kubun][idx];
}
function gakechiRate(ratio, dirIdx){
  if(!(ratio>=0.10)) return 1.00;
  let v=1.00;
  for(const [lo,r] of T_GAKECHI) if(ratio>=lo) v=r[dirIdx];
  return v;
}
function tokkeiRate(ratio){
  if(!(ratio>=0.10)) return 1.00;
  let v=1.00;
  for(const [lo,r] of T_TOKKEI) if(ratio>=lo) v=r;
  return v;
}
function taxBracket(x){ for(const [lim,r,d] of TAX_TABLE) if(x<=lim) return [r,d]; return [0,0]; }

/* 区分所有補正率（令和6年1月1日以後の相続・遺贈・贈与）
   国税庁 令和5年9月28日付法令解釈通達「居住用の区分所有財産の評価について」 */
function kubunShoyuHosei({chikunen, soukaisu, shozaikai, chika, senyuArea, shikichiArea}){
  const floor3=x=>Math.floor(x*1000)/1000, ceil3=x=>Math.ceil(x*1000)/1000;
  const Y = Math.max(1, Math.ceil(chikunen));            // 築年数（1年未満切上げ）
  const A = -0.033*Y;
  let idx = floor3(Math.min(1, soukaisu/33));            // 総階数指数（第4位切捨て・1超は1）
  const B = floor3(idx*0.239);
  const C = 0.018*(chika?0:shozaikai);                   // 地階は零階
  const kyousho = senyuArea>0 ? ceil3(shikichiArea/senyuArea) : 0;   // 敷地持分狭小度（第4位切上げ）
  const D = -ceil3(kyousho*1.195);
  const K = Math.round((A+B+C+D+3.220)*1000)/1000;       // 評価乖離率
  let hosei=1.0, level=null, note='';
  if(K<=0){ note='評価乖離率が0以下のため補正なし（個別に税理士へ確認要）'; }
  else{
    level=1/K;
    if(level<0.6) hosei=Math.round(K*0.6*1000)/1000;
    else if(level>1) hosei=K;
  }
  return {A:Math.round(A*1000)/1000,B,C:Math.round(C*1000)/1000,D:Math.round(D*1000)/1000,K,level,hosei,kyousho,note};
}
